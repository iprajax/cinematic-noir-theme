#!/usr/bin/env bash
#
# Snapshot this Mac's appearance settings into a replayable file.
#
#   bash noir-capture.sh                 # writes ./my-settings.sh next to this script
#   bash noir-capture.sh --out FILE      # writes somewhere else (noir-setup.sh uses
#                                        # this to back up the target Mac first)
#
# The output is plain `defaults write` / `defaults delete` lines — read it, edit
# it, and noir-setup.sh replays it on another Mac. Keys that are unset here are
# written as deletes, so the other Mac ends up matching, not just "added to".

set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
NOIR="${HOME}/Pictures/Editorial Noir"
OUT="${HERE}/my-settings.sh"
[[ "${1:-}" == "--out" && -n "${2:-}" ]] && OUT="$2"

say() { printf '\033[38;5;180m›\033[0m %s\n' "$*" >&2; }

# domain|key — the appearance surface: Appearance pane, Dock, hot corners,
# desktop behaviour, screen saver timing, Terminal default profile.
KEYS=(
  "-g|AppleInterfaceStyleSwitchesAutomatically"
  "-g|AppleAccentColor"
  "-g|AppleAquaColorVariant"
  "-g|AppleHighlightColor"
  "-g|AppleIconAppearanceTheme"
  "-g|AppleIconAppearanceTintColor"
  "-g|AppleReduceDesktopTinting"
  "-g|AppleShowScrollBars"
  "-g|NSTableViewDefaultSizeMode"
  "-g|AppleMiniaturizeOnDoubleClick"
  "-g|AppleActionOnDoubleClick"
  "-g|AppleWindowTabbingMode"
  "com.apple.dock|tilesize"
  "com.apple.dock|magnification"
  "com.apple.dock|largesize"
  "com.apple.dock|orientation"
  "com.apple.dock|autohide"
  "com.apple.dock|autohide-delay"
  "com.apple.dock|show-recents"
  "com.apple.dock|mineffect"
  "com.apple.dock|minimize-to-application"
  "com.apple.dock|wvous-tl-corner"
  "com.apple.dock|wvous-tl-modifier"
  "com.apple.dock|wvous-tr-corner"
  "com.apple.dock|wvous-tr-modifier"
  "com.apple.dock|wvous-bl-corner"
  "com.apple.dock|wvous-bl-modifier"
  "com.apple.dock|wvous-br-corner"
  "com.apple.dock|wvous-br-modifier"
  "com.apple.WindowManager|EnableStandardClickToShowDesktop"
  "com.apple.WindowManager|EnableTiledWindowMargins"
  "com.apple.Terminal|Default Window Settings"
  "com.apple.Terminal|Startup Window Settings"
  "-currentHost com.apple.screensaver|idleTime"
)

line_for() {   # $1 = domain (may be prefixed "-currentHost "), $2 = key
  local dom="$1" key="$2" host="" type val flag
  if [[ "$dom" == "-currentHost "* ]]; then host="-currentHost "; dom="${dom#-currentHost }"; fi
  # shellcheck disable=SC2086  # $host is empty or one word
  if ! type="$(defaults $host read-type "$dom" "$key" 2>/dev/null)"; then
    printf 'defaults %sdelete %s %q 2>/dev/null || true\n' "$host" "$dom" "$key"
    return
  fi
  # shellcheck disable=SC2086
  val="$(defaults $host read "$dom" "$key")"
  case "$type" in
    *integer*) flag="-int" ;;
    *float*)   flag="-float" ;;
    *boolean*) flag="-bool"; [[ "$val" == 1 ]] && val=true || val=false ;;
    *string*)  flag="-string" ;;
    *) printf '# skipped %s %s (%s — not a scalar)\n' "$dom" "$key" "$type"; return ;;
  esac
  printf 'defaults %swrite %s %q %s %q\n' "$host" "$dom" "$key" "$flag" "$val"
}

say "Capturing appearance settings…"
{
  echo "# Appearance snapshot"
  echo "# macOS $(sw_vers -productVersion), $(date '+%Y-%m-%d %H:%M')"
  echo "# Generated by noir-capture.sh. Replayed by noir-setup.sh. Safe to edit."
  echo

  echo "# Light / Dark — through System Events so it takes effect live."
  if [[ "$(defaults read -g AppleInterfaceStyleSwitchesAutomatically 2>/dev/null)" == 1 ]]; then
    echo "# (Auto: the key below handles it)"
  elif [[ "$(defaults read -g AppleInterfaceStyle 2>/dev/null)" == Dark ]]; then
    echo "osascript -e 'tell application \"System Events\" to tell appearance preferences to set dark mode to true'"
  else
    echo "osascript -e 'tell application \"System Events\" to tell appearance preferences to set dark mode to false'"
  fi
  echo

  for entry in "${KEYS[@]}"; do
    line_for "${entry%%|*}" "${entry#*|}"
  done
  echo

  # Wallpaper: stored by file name inside the noir folder so it works under any
  # user name. A wallpaper from elsewhere is copied in so it travels too.
  wp="$(osascript -e 'tell application "System Events" to get picture of desktop 1' 2>/dev/null || true)"
  if [[ -n "$wp" && -f "$wp" ]]; then
    if [[ "$(dirname "$wp")" != "$NOIR" && -d "$NOIR" && "$OUT" == "${HERE}/my-settings.sh" ]]; then
      cp -n "$wp" "$NOIR/" && say "Copied your wallpaper into the noir folder so it travels: $(basename "$wp")"
    fi
    if [[ "$(dirname "$wp")" == "$NOIR" || -f "$NOIR/$(basename "$wp")" ]]; then
      printf 'WALLPAPER=%q\n' "$(basename "$wp")"
    else
      printf 'WALLPAPER_ABS=%q\n' "$wp"
    fi
  fi

  # Which screen saver is picked. macOS keeps this (and the Photos folder
  # source) in a store a script shouldn't write, so this only drives the
  # "one click left" message at the end of setup.
  saver="$(python3 - <<'PY' 2>/dev/null || true
import plistlib, os
p = os.path.expanduser("~/Library/Application Support/com.apple.wallpaper/Store/Index.plist")
c = plistlib.load(open(p, "rb"))["AllSpacesAndDisplays"]["Idle"]["Content"]["Choices"][0]
m = plistlib.loads(c["Configuration"]).get("module", {}).get("relative", "")
print(os.path.basename(m.rstrip("/")))
PY
)"
  printf 'SAVER=%q\n' "${saver:-unknown}"
} > "$OUT"

say "Wrote ${OUT}"
